def all_items():
    """Returns {(modid, texture_name): image}."""
    out = {}
    out[("urcore", "item/crown")] = COIN.render(P.GOLD)
    out[("urcore", "item/crown_purse")] = PURSE.render(P.LEATHER, secondary=P.GOLD)
    out[("urskills", "item/skill_book")] = BOOK.render(P.CLOTH_RED, secondary=P.PARCHMENT, tertiary=P.GOLD)
    for school, ramp in P.SCHOOLS.items():
        out[("urmagic", f"item/spell_tome_{school}")] = TOME.render(ramp, secondary=P.PARCHMENT, tertiary=P.GOLD)
    out[("urmagic", "item/bound_sword")] = SWORD.render(P.CONJURATION, secondary=P.CLOTH_PURPLE, tertiary=P.AMETHYST)
    out[("urmagic", "item/magicka_potion")] = POTION.render(P.SAPPHIRE, secondary=P.WOOD)
    out[("urmagic", "item/stamina_potion")] = POTION.render(P.EMERALD, secondary=P.WOOD)
    out[("urquests", "item/quest_scroll")] = SCROLL.render(P.PARCHMENT, secondary=P.WOOD)
    notice = canvas()
    notice.alpha_composite(G.parchment(12, seed=11), (2, 2))
    out[("urquests", "item/bounty_notice")] = outline(notice, P.OUTLINE)
    return out
